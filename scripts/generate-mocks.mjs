import { execFileSync } from 'node:child_process';
import process from 'node:process';
// Generate routing from the same OpenAPI contract used to generate API types.
import { readFileSync, writeFileSync } from 'node:fs';
const spec = JSON.parse(readFileSync('api/ui-prototype.openapi.json', 'utf8'));
const routes = Object.entries(spec.paths).flatMap(([path, methods]) =>
  Object.entries(methods)
    .filter(([method]) => ['get', 'post', 'patch', 'delete'].includes(method))
    .map(
      ([method, operation]) =>
        `  http.${method}('${path.replace(/\{(\w+)\}/g, ':$1')}', scenarios.${operation.operationId}),`,
    ),
);
writeFileSync(
  'apps/frontend/src/mocks/handlers.ts',
  `// Generated by scripts/generate-mocks.mjs. Do not edit.\nimport { http } from 'msw';\nimport * as scenarios from './scenarios';\nexport const handlers = [\n${routes.join('\n')}\n];\n`,
);
const operations = Object.entries(spec.paths).flatMap(([path, methods]) =>
  Object.entries(methods)
    .filter(([method]) => ['get', 'post', 'patch'].includes(method))
    .map(([method, op]) => ({ path, method, id: op.operationId })),
);
const endpoints = Object.fromEntries(operations.map((op) => [op.id, op]));
const list = endpoints.listPhotos,
  create = endpoints.createPhoto,
  update = endpoints.updatePhoto;
writeFileSync(
  'apps/frontend/src/lib/api.ts',
  `// Generated from api/ui-prototype.openapi.json by scripts/generate-mocks.mjs. Do not edit.\nimport type {operations} from './api.generated';\ntype Response<K extends keyof operations> = operations[K]['responses'][200]['content']['application/json'];\nasync function request<T>(url:string,init?:RequestInit):Promise<T>{const response=await fetch(url,init);if(!response.ok)throw new Error('通信に失敗しました。もう一度お試しください。');return response.json();}\nexport const api={\nlist:()=>request<Response<'${list.id}'>>('${list.path}'),\nupdate:(id:string,body:operations['${update.id}']['requestBody']['content']['application/json'])=>request<Response<'${update.id}'>>('${update.path}'.replace('{id}',encodeURIComponent(id)),{method:'${update.method.toUpperCase()}',headers:{'Content-Type':'application/json'},body:JSON.stringify(body)}),\ncreate:(src:string,name:string)=>request<Response<'${create.id}'>>('${create.path}',{method:'${create.method.toUpperCase()}',headers:{'Content-Type':'application/json'},body:JSON.stringify({src,name} satisfies operations['${create.id}']['requestBody']['content']['application/json'])})\n};\n`,
);

execFileSync(
  process.execPath,
  [
    'node_modules/prettier/bin/prettier.cjs',
    '--write',
    'apps/frontend/src/lib/api.generated.ts',
    'apps/frontend/src/lib/api.ts',
    'apps/frontend/src/mocks/handlers.ts',
  ],
  { stdio: 'inherit' },
);
